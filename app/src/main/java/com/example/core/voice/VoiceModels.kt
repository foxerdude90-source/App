package com.example.core.voice

enum class VoiceCategory(val label: String) {
    ALL("All"),
    CLONED("Cloned"),
    NARRATOR("Narrator"),
    PODCAST("Podcast"),
    CREATOR("Creator"),
    CINEMA("Cinema"),
    CHARACTER("Character"),
    CALM("Calm"),
}

enum class PhrasingStyle(
    val label: String,
    val commaPauseMs: Int,
    val sentencePauseMs: Int,
    val paragraphPauseMs: Int,
) {
    TIGHT("Tight", 120, 260, 420),
    NATURAL("Natural", 220, 460, 740),
    DRAMATIC("Dramatic", 360, 720, 1100),
}

enum class StudioRoomPreset(
    val label: String,
    val wetMix: Float,
    val decay: Float,
) {
    DRY_BOOTH("Dry Booth", 0.0f, 0.0f),
    PODCAST_ROOM("Podcast Room", 0.14f, 0.32f),
    CINEMA_HALL("Cinema Hall", 0.28f, 0.56f),
}

data class VoiceProfile(
    val id: String,
    val name: String,
    val tagline: String,
    val category: VoiceCategory,
    val isCloned: Boolean = false,
    val targetF0Hz: Float = 150f,
    val ttsBasePitch: Float = 1.0f,
    val ttsBaseRate: Float = 1.0f,
    val dspPitchSemitones: Float = 0f,
    val lowShelfDb: Float = 0f,
    val midPeakDb: Float = 0f,
    val highShelfDb: Float = 0f,
    val breathiness: Float = 0.05f,
    val warmthDrive: Float = 0.12f,
    val defaultRoomWet: Float = 0.05f,
    val cyberModHz: Float = 0f,
    val localeTag: String = "en-US",
    val preferLowVoice: Boolean = false,
    val sourceSummary: String? = null,
)

data class VoiceGenerationParams(
    val speed: Float = 1.0f,               // 0.60 .. 1.60
    val pitchSemitones: Float = 0f,        // -8.0 .. +8.0
    val stability: Float = 0.72f,          // 0.0 .. 1.0 (reliability / consistency)
    val clarityBoost: Float = 0.68f,       // 0.0 .. 1.0 (spectral similarity & presence)
    val styleExaggeration: Float = 0.45f,  // 0.0 .. 1.0 (timbre warmth & expression)
    val phrasing: PhrasingStyle = PhrasingStyle.NATURAL,
    val roomPreset: StudioRoomPreset = StudioRoomPreset.DRY_BOOTH,
)

data class ClonedVoiceAnalysis(
    val fundamentalHz: Float,
    val pitchStdDevHz: Float,
    val lowEnergyRatio: Float,
    val midEnergyRatio: Float,
    val highEnergyRatio: Float,
    val breathiness: Float,
    val speakingTempoRatio: Float,
    val durationSec: Float,
    val voiceDescriptor: String,
)

