package com.example.core.voice

enum class VoiceCategory(val label: String) {
    ALL("All"),
    CLONED("Cloned"),
    NARRATOR("Narrator"),
    PODCAST("Podcast"),
    CREATOR("Creator"),
    CINEMA("Cinema"),
    CHARACTER("Character"),
    CALM("Calm"),
}

enum class PhrasingStyle(
    val label: String,
    val commaPauseMs: Int,
    val sentencePauseMs: Int,
    val paragraphPauseMs: Int,
) {
    TIGHT("Tight", 110, 240, 380),
    NATURAL("Natural", 200, 420, 680),
    DRAMATIC("Dramatic", 340, 680, 1050),
}

enum class StudioRoomPreset(
    val label: String,
    val wetMix: Float,
    val decay: Float,
) {
    DRY_BOOTH("Dry Booth", 0.0f, 0.0f),
    PODCAST_ROOM("Podcast Room", 0.09f, 0.28f),
    CINEMA_HALL("Cinema Hall", 0.20f, 0.48f),
}

data class VoiceProfile(
    val id: String,
    val name: String,
    val tagline: String,
    val category: VoiceCategory,
    val isCloned: Boolean = false,
    val targetF0Hz: Float = 150f,
    val ttsBasePitch: Float = 1.0f,         // Kept inside natural human neural TTS range (0.85..1.16)
    val ttsBaseRate: Float = 1.0f,
    val dspPitchSemitones: Float = 0f,      // 0f by default for crystal-clean studio clarity
    val lowShelfDb: Float = 0f,             // Musical broadcast EQ (-3..+3.5 dB)
    val midPeakDb: Float = 0f,
    val highShelfDb: Float = 0f,
    val breathiness: Float = 0f,            // Maps to silky 7.5 kHz studio condenser air shelf (NO noise!)
    val warmthDrive: Float = 0.05f,         // Gentle subtle analog glue (NO clipping/distortion)
    val defaultRoomWet: Float = 0.0f,       // Dry by default so voices stay crisp and clear
    val cyberModHz: Float = 0f,
    val localeTag: String = "en-US",
    val preferLowVoice: Boolean = false,
    val voiceVariantSlot: Int = 0,          // Spreads profiles across distinct installed neural voices
    val sourceSummary: String? = null,
)

data class VoiceGenerationParams(
    val speed: Float = 1.0f,                // 0.60 .. 1.60
    val pitchSemitones: Float = 0f,         // -6.0 .. +6.0
    val stability: Float = 0.78f,           // 0.0 .. 1.0 (clause-to-clause cadence & pitch consistency)
    val clarityBoost: Float = 0.65f,        // 0.0 .. 1.0 (broadcast presence & air polish)
    val styleExaggeration: Float = 0.35f,   // 0.0 .. 1.0 (vocal EQ contour & expressive inflection)
    val phrasing: PhrasingStyle = PhrasingStyle.NATURAL,
    val roomPreset: StudioRoomPreset = StudioRoomPreset.DRY_BOOTH,
)

data class ClonedVoiceAnalysis(
    val fundamentalHz: Float,
    val pitchStdDevHz: Float,
    val lowEnergyRatio: Float,
    val midEnergyRatio: Float,
    val highEnergyRatio: Float,
    val breathiness: Float,
    val speakingTempoRatio: Float,
    val durationSec: Float,
    val voiceDescriptor: String,
)

